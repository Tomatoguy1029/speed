#!/usr/bin/env python3
"""Embed the saved pump flight profile in its runtime shader, without Godot.

The visual editor keeps the generic shader. This explicit authoring command
writes only the flight shader; impact and death debris use separate resources.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data/visuals/effect_settings.tres"
TEMPLATE = ROOT / "shaders/pump_shell.gdshader"
OUTPUT = ROOT / "shaders/pump_shell_runtime.gdshader"
DATA = ROOT / "data/visuals/pump_shell_runtime.tres"
KEY = "res://scenes/attacks/shell.tscn"
PREFIX = "shader/pump_shell/"


def f32(value):
    return struct.unpack("f", struct.pack("f", float(value)))[0]


def literal(value):
    return repr(f32(value))


def linear(value):
    if value < f32(0.04045):
        return f32(value * f32(1 / 12.92))
    return f32(math.pow(f32((value + 0.055) / 1.055), f32(2.4)))


def specialize():
    source = SOURCE.read_text()
    profile = re.search(r'^"' + re.escape(KEY) + r'": \{\n(.*?)^\}', source, re.M | re.S)
    if not profile:
        raise ValueError("Missing pump flight profile")
    saved = dict(re.findall(r'^"([^"]+)": (.+?)(?:,)?$', profile[1], re.M))
    overrides = {key[len(PREFIX):]: value for key, value in saved.items() if key.startswith(PREFIX)}
    template = TEMPLATE.read_text()
    header, body = template.split("varying vec2 bolt_pixel;", 1)
    colors = []
    found = set()

    def constant(match):
        kind, name, _hint, default = match.groups()
        if name in {"enemy%d" % i for i in range(7)} | {"clock", "contents_count", "contents_fill", "trail_reach"}:
            return match[0]
        found.add(name)
        value = overrides.get(name, default)
        if value is None:
            raise ValueError("Missing shader default: " + name)
        if kind == "float":
            return "const float " + name + " = " + literal(value) + ";"
        if kind != "vec4":
            raise ValueError("Unsupported artist uniform: " + name)
        channels = re.fullmatch(r'(?:vec4|Color)\(([^)]+)\)', value.strip())
        if not channels:
            raise ValueError("Unsupported color: " + value)
        rgba = [f32(v) for v in channels[1].split(",")]
        if len(rgba) != 4:
            raise ValueError("Expected RGBA: " + name)
        colors.append(name)
        srgb = "vec4(" + ", ".join(map(literal, rgba)) + ")"
        converted = "vec4(" + ", ".join(map(literal, [linear(c) for c in rgba[:3]] + rgba[3:])) + ")"
        return "const vec4 " + name + " = " + converted + ";\nconst vec4 " + name + "_srgb = " + srgb + ";"

    header = re.sub(r'^uniform (\w+) (\w+)\s*(:[^=;]+)?(?:=\s*([^;]+))?;', constant, header, flags=re.M)
    if set(overrides) - found:
        raise ValueError("Unknown saved uniforms: " + str(set(overrides) - found))
    header = re.sub(r'^group_uniforms[^\n]*\n', "", header, flags=re.M)
    # source_color uniforms convert automatically; constants retain both paths.
    header += "uniform bool linear_colors = true;\n"
    for name in colors:
        body = re.sub(r'\b' + name + r'\b', "(linear_colors ? " + name + " : " + name + "_srgb)", body)
    profile_hash = hashlib.sha256(profile[0].encode()).hexdigest()
    template_hash = hashlib.sha256(template.encode()).hexdigest()
    metadata = ("// Generated by tools/art/bake_pump_shell.py; edit the saved profile, then rebake.\n"
                "// Pump flight profile SHA256: " + profile_hash + "\n"
                "// Editable shader SHA256: " + template_hash + "\n")
    return metadata + header + "varying vec2 bolt_pixel;" + body, len(found), len(overrides)


def generate():
    source_bytes = SOURCE.read_bytes()
    shader, count, overrides = specialize()
    profile = re.search(r'^"' + re.escape(KEY) + r'": \{\n(.*?)^\}', source_bytes.decode(), re.M | re.S)
    saved = dict(re.findall(r'^"([^"]+)": (.+?)(?:,)?$', profile[1], re.M))
    tint = saved.get("effect_tint", "Color(1, 1, 1, 1)")
    if not re.fullmatch(r'Color\([\d.eE+, -]+\)', tint):
        raise ValueError("Unsupported flight tint: " + tint)
    inputs = {"res://" + path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest() for path in
              ("tools/art/bake_pump_shell.py", "shaders/pump_shell.gdshader", "scripts/render/attacks/shell.gd")}
    metadata = ('[gd_resource type="Resource" format=3]\n\n[resource]\n'
                'metadata/bake_version = 1\nmetadata/source_sha256 = "' + hashlib.sha256(source_bytes).hexdigest() + '"\n'
                'metadata/values = {"flight_scale": ' + repr(float(saved.get("flight_scale", "1.0"))) + ', "effect_tint": ' + tint + '}\n'
                'metadata/inputs = ' + json.dumps(inputs, indent=4) + '\n'
                'metadata/saved_profiles = ' + json.dumps({KEY: hashlib.sha256(profile[0].encode()).hexdigest()}, indent=4) + '\n'
                'metadata/outputs = ' + json.dumps({"res://shaders/pump_shell_runtime.gdshader": hashlib.sha256(shader.encode()).hexdigest()}, indent=4) + '\n')
    if SOURCE.read_bytes() != source_bytes:
        raise ValueError("Saved profiles changed during flight bake; rerun from the latest values")
    return {OUTPUT: shader, DATA: metadata}, count, overrides


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare the embedded output without writing")
    args = parser.parse_args()
    outputs, count, overrides = generate()
    if args.check:
        if any(not path.exists() or path.read_text() != text for path, text in outputs.items()):
            raise SystemExit("Pump flight runtime shader differs from its saved profile/defaults")
        print("Pump flight runtime shader matches %d artist constants (%d saved overrides)." % (count, overrides))
    else:
        for path, text in outputs.items():
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
        print("Embedded %d pump flight constants (%d saved overrides)." % (count, overrides))
